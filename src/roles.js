export function planPrompt(task, projectInfo) {
  return `TASK:\n${task}\n\nPROJECT (working directory):\n${projectInfo}\n\nCreate the plan.`;
}

// agentci parses the project itself and ships the result in the prompt, so agents don't
// have to spend tokens listing and grepping the tree.
const MAP_HINT = 'The PROJECT MAP below was generated by agentci (static analysis, always current): '
  + 'every file with its line count, exported symbols and which project files it imports. '
  + 'Use it instead of listing/globbing the tree, and only read the few files you really need to change or understand.';

export function withMap(prompt, mapText) {
  return mapText ? `${prompt}\n\n${MAP_HINT}\n\n${mapText}` : prompt;
}

function planContext(state) {
  const todos = state.todos.map((t) => `- ${t.id} [${t.status}] ${t.title}`).join('\n');
  return `OVERALL TASK:\n${state.task}\n\nPLAN:\n${state.summary}\n${todos}`;
}

export function implementPrompt(state, todo) {
  return `${planContext(state)}\n\nYOUR TODO NOW: ${todo.id} – ${todo.title}\nDetails: ${todo.details}\nAcceptance: ${todo.acceptance}\n\nImplement it now.`;
}

export function fixPrompt(state, todo, problems) {
  return `${planContext(state)}\n\nCURRENT TODO: ${todo.id} – ${todo.title}\nDetails: ${todo.details}\n\nPROBLEMS TO FIX:\n${problems}\n\nFix these problems now.`;
}

export function reviewPrompt(state, todo, diff, checkSummary) {
  return `${planContext(state)}\n\nTODO UNDER REVIEW: ${todo.id} – ${todo.title}\nDetails: ${todo.details}\nAcceptance: ${todo.acceptance}\n\nAUTOMATIC CHECKS: ${checkSummary}\n\nDIFF:\n${diff || '(no changes)'}\n\nReview it.`;
}

export function testPrompt(state, todo, changedFiles) {
  return `${planContext(state)}\n\nJUST IMPLEMENTED: ${todo.id} – ${todo.title}\nDetails: ${todo.details}\nChanged files: ${changedFiles.join(', ') || '(none)'}\n\nWrite the tests now.`;
}

export function docsPrompt(state) {
  return `${planContext(state)}\n\nAll todos are done. Update the documentation now.`;
}

export function formatReviewIssues(review) {
  return (review.issues || [])
    .filter((i) => i.severity !== 'minor')
    .map((i) => `- [${i.severity}] ${i.file}: ${i.description}`)
    .join('\n');
}
