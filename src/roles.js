// System prompts and output schemas for each agent role.
// Schemas are "strict" (all props required, no extra props) so they work for Claude and Codex.

const LANG = 'Write all prose (titles, summaries, issues) in the same language the task is written in.';

export const PLAN_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['summary', 'todos'],
  properties: {
    summary: { type: 'string' },
    todos: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['id', 'title', 'details', 'dependsOn', 'acceptance'],
        properties: {
          id: { type: 'string' },
          title: { type: 'string' },
          details: { type: 'string' },
          dependsOn: { type: 'array', items: { type: 'string' } },
          acceptance: { type: 'string' },
        },
      },
    },
  },
};

export const REVIEW_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['approved', 'summary', 'issues'],
  properties: {
    approved: { type: 'boolean' },
    summary: { type: 'string' },
    issues: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['severity', 'file', 'description'],
        properties: {
          severity: { type: 'string', enum: ['critical', 'major', 'minor'] },
          file: { type: 'string' },
          description: { type: 'string' },
        },
      },
    },
  },
};

